//! `osd` event topic (N0043): transient feedback for user-visible changes.
//! The topic's state is only its health (`core_services::OsdState`); every change is an
//! `ev` message named `changed` whose data is an [`OsdEvent`]. The envelope `seq` is the
//! per-topic event sequence. Events are never replayed to a new subscriber.
use crate::MAX_SAFE_INTEGER;
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::collections::BTreeMap;

pub const TOPIC: &str = "osd";
pub const EVENT: &str = "changed";

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum OsdKind {
    /// Default output volume or mute. `label` is the output's description.
    Volume,
    /// The default output device changed. Carries the new device's level too.
    Output,
    /// Default input volume or mute.
    Microphone,
    /// Display brightness; `device` is the output name.
    Brightness,
    /// Keyboard backlight; `max` is the number of steps.
    Keyboard,
    /// `value` 1 on, 0 off.
    NightLight,
    /// `label` is `power-saver`, `balanced` or `performance`.
    PowerProfile,
    /// `value` 1 on, 0 off.
    Capslock,
}

/// `value` is a level fraction (volume may exceed 1) or 1/0 for the two toggles.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct OsdEvent {
    pub kind: OsdKind,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(range(min = 0.0))]
    pub value: Option<f64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(range(min = 1, max = 65535))]
    pub max: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub muted: Option<bool>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(length(max = 256))]
    pub label: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(length(max = 128))]
    pub device: Option<String>,
    /// Unix milliseconds when the change was observed.
    #[schemars(range(min = 0, max = 9007199254740991_u64))]
    pub ts: u64,
}

impl OsdEvent {
    pub fn new(kind: OsdKind, ts: u64) -> Self {
        Self {
            kind,
            value: None,
            max: None,
            muted: None,
            label: None,
            device: None,
            ts,
        }
    }
    pub fn valid(&self) -> bool {
        let toggle = matches!(self.kind, OsdKind::NightLight | OsdKind::Capslock);
        self.ts <= MAX_SAFE_INTEGER
            && self.value.is_none_or(|v| {
                v.is_finite()
                    && v >= 0.0
                    && match self.kind {
                        OsdKind::Brightness | OsdKind::Keyboard => v <= 1.0,
                        _ if toggle => v == 0.0 || v == 1.0,
                        _ => true,
                    }
            })
            && self.max.is_none_or(|m| (1..=65535).contains(&m))
            && self.label.as_ref().is_none_or(|s| s.len() <= 256)
            && self.device.as_ref().is_none_or(|s| s.len() <= 128)
            && match self.kind {
                OsdKind::Keyboard => self.value.is_some() && self.max.is_some(),
                OsdKind::NightLight | OsdKind::Capslock | OsdKind::Brightness => {
                    self.value.is_some()
                }
                OsdKind::PowerProfile => self.label.is_some(),
                _ => true,
            }
    }
}

pub(crate) fn exports() -> BTreeMap<String, String> {
    let schema = serde_json::to_value(schemars::schema_for!(OsdEvent)).expect("osd schema");
    let mut files = BTreeMap::new();
    files.insert(
        "protocol/schema/osd-event.json".into(),
        serde_json::to_string_pretty(&schema).expect("schema JSON") + "\n",
    );
    files.insert(
        "protocol/luau/osd.d.luau".into(),
        format!(
            "-- Generated by nacre-protocol; do not edit. MIT OR Apache-2.0.\nexport type OsdEvent = {}\nreturn {{}}\n",
            crate::artifacts::luau(&schema)
        ),
    );
    let ev = |seq: u64, data: serde_json::Value| json!({"t":"ev","topic":TOPIC,"name":EVENT,"seq":seq,"data":data});
    let frames = [
        json!({"t":"snap","topic":TOPIC,"seq":0,"data":{"health":{"available":true,"stale":false}}}),
        ev(
            1,
            json!({"kind":"volume","value":0.5,"muted":false,"label":"Speakers","device":"alsa_output.pci-0000_00_1f.3.analog-stereo","ts":1800000000100_u64}),
        ),
        ev(
            2,
            json!({"kind":"output","value":0.3,"muted":false,"label":"Headphones","device":"bluez_output.00_11_22","ts":1800000001000_u64}),
        ),
        ev(
            3,
            json!({"kind":"microphone","value":0.0,"muted":true,"label":"Built-in microphone","device":"alsa_input.pci-0000_00_1f.3.analog-stereo","ts":1800000002000_u64}),
        ),
        ev(
            4,
            json!({"kind":"brightness","value":0.75,"device":"eDP-1","ts":1800000003000_u64}),
        ),
        ev(
            5,
            json!({"kind":"keyboard","value":0.5,"max":2,"ts":1800000004000_u64}),
        ),
        ev(
            6,
            json!({"kind":"night_light","value":1.0,"ts":1800000005000_u64}),
        ),
        ev(
            7,
            json!({"kind":"power_profile","label":"performance","ts":1800000006000_u64}),
        ),
        ev(
            8,
            json!({"kind":"capslock","value":1.0,"ts":1800000007000_u64}),
        ),
        json!({"t":"lost","topic":TOPIC,"from":9,"to":12}),
    ];
    files.insert(
        "protocol/fixtures/osd.jsonl".into(),
        frames
            .iter()
            .map(|frame| serde_json::to_string(frame).expect("osd transcript") + "\n")
            .collect(),
    );
    files
}

#[cfg(test)]
mod tests {
    use super::*;
    fn event(kind: OsdKind) -> OsdEvent {
        OsdEvent::new(kind, 1)
    }
    #[test]
    fn each_kind_has_its_required_fields() {
        let mut v = event(OsdKind::Volume);
        assert!(v.valid());
        v.value = Some(1.2);
        assert!(v.valid(), "volume may exceed one");
        v.value = Some(f64::NAN);
        assert!(!v.valid());
        let mut b = event(OsdKind::Brightness);
        assert!(!b.valid());
        b.value = Some(1.01);
        assert!(!b.valid());
        b.value = Some(1.0);
        assert!(b.valid());
        let mut k = event(OsdKind::Keyboard);
        k.value = Some(0.5);
        assert!(!k.valid());
        k.max = Some(2);
        assert!(k.valid());
        for kind in [OsdKind::Capslock, OsdKind::NightLight] {
            let mut t = event(kind);
            assert!(!t.valid());
            t.value = Some(0.5);
            assert!(!t.valid());
            t.value = Some(1.0);
            assert!(t.valid());
        }
        let mut p = event(OsdKind::PowerProfile);
        assert!(!p.valid());
        p.label = Some("balanced".into());
        assert!(p.valid());
        p.device = Some("d".repeat(129));
        assert!(!p.valid());
    }
    #[test]
    fn wire_names_are_snake_case_and_absent_fields_are_omitted() {
        let mut e = event(OsdKind::PowerProfile);
        e.label = Some("balanced".into());
        assert_eq!(
            serde_json::to_value(&e).unwrap(),
            json!({"kind":"power_profile","label":"balanced","ts":1})
        );
        let back: OsdEvent =
            serde_json::from_value(json!({"kind":"night_light","value":1.0,"ts":2,"future":1}))
                .unwrap();
        assert_eq!(back.kind, OsdKind::NightLight);
    }
    #[test]
    fn exported_transcript_events_are_valid() {
        let files = exports();
        for line in files["protocol/fixtures/osd.jsonl"].lines() {
            let frame: serde_json::Value = serde_json::from_str(line).unwrap();
            if frame["t"] == "ev" {
                let e: OsdEvent = serde_json::from_value(frame["data"].clone()).unwrap();
                assert!(e.valid(), "{line}");
            }
        }
    }
}
