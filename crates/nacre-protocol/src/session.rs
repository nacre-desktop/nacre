//! N0317: `session.state`, the logind lock and sleep flags shells pause and resync on.
//! The `session` topic stays the daemon's session-policy record.
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::collections::BTreeMap;

pub const STATE_TOPIC: &str = "session.state";

/// `locked` is logind's `LockedHint` for the user's display session. `preparing_sleep` is
/// true from logind's `PrepareForSleep(true)` until `PrepareForSleep(false)`, so its fall
/// to false marks a resume. `sleeping` carries the same window (nothing runs while the
/// system is suspended, so the daemon cannot tell the two apart). `revision` is 0 until
/// logind has been read, then increases by one with every change.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct SessionState {
    pub locked: bool,
    pub sleeping: bool,
    pub preparing_sleep: bool,
    #[schemars(range(max = 9007199254740991_u64))]
    pub revision: u64,
}

pub(crate) fn exports() -> BTreeMap<String, String> {
    let schema = serde_json::to_value(schemars::schema_for!(SessionState)).expect("schema");
    let types = format!(
        "-- Generated by nacre-protocol; do not edit. MIT OR Apache-2.0.\nexport type SessionState = {}\nreturn {{}}\n",
        crate::artifacts::luau(&schema)
    );
    let frames = [
        json!({"t":"sub","topics":[STATE_TOPIC]}),
        json!({"t":"snap","topic":STATE_TOPIC,"seq":0,"data":{"locked":false,"sleeping":false,"preparing_sleep":false,"revision":0}}),
        json!({"t":"patch","topic":STATE_TOPIC,"base":0,"seq":1,"data":{"revision":1}}),
        json!({"t":"patch","topic":STATE_TOPIC,"base":1,"seq":2,"data":{"locked":true,"revision":2}}),
        json!({"t":"patch","topic":STATE_TOPIC,"base":2,"seq":3,"data":{"sleeping":true,"preparing_sleep":true,"revision":3}}),
        json!({"t":"patch","topic":STATE_TOPIC,"base":3,"seq":4,"data":{"sleeping":false,"preparing_sleep":false,"revision":4}}),
        json!({"t":"patch","topic":STATE_TOPIC,"base":4,"seq":5,"data":{"locked":false,"revision":5}}),
    ];
    BTreeMap::from([
        (
            "protocol/schema/session-state.json".into(),
            serde_json::to_string_pretty(&schema).expect("schema") + "\n",
        ),
        ("protocol/luau/session.d.luau".into(), types),
        (
            "protocol/fixtures/session-state.jsonl".into(),
            frames
                .iter()
                .map(|frame| serde_json::to_string(frame).expect("fixture") + "\n")
                .collect(),
        ),
    ])
}
