//! N0056: subscription-leased, consent-gated city photography.
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::collections::BTreeMap;

pub const TOPIC: &str = "dashboard.weather_photo";
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum Status {
    Disabled,
    Idle,
    Paused,
    WaitingLocation,
    Loading,
    Ready,
    Unavailable,
}
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct Location {
    #[schemars(length(max = 100))]
    pub city: String,
    #[schemars(range(min = -90.0, max = 90.0))]
    pub latitude: f64,
    #[schemars(range(min = -180.0, max = 180.0))]
    pub longitude: f64,
}
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct Asset {
    /// Absolute path below the user's daemon weather-photo cache; never a URL.
    #[schemars(length(max = 4096))]
    pub path: String,
    /// Unix seconds; also the decoded-image cache version.
    #[schemars(range(min = 0.0, max = 9007199254740991.0))]
    pub checked: f64,
    #[schemars(length(max = 160))]
    pub author: String,
    #[schemars(length(max = 40))]
    pub license: String,
    #[schemars(length(max = 2048))]
    pub source: String,
}
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct State {
    pub enabled: bool,
    pub ready: bool,
    pub status: Status,
    pub location: Option<Location>,
    pub asset: Option<Asset>,
}
pub(crate) fn exports() -> BTreeMap<String, String> {
    let schema = serde_json::to_value(schemars::schema_for!(State)).expect("photo schema");
    let mut types =
        String::from("-- Generated by nacre-protocol; do not edit. MIT OR Apache-2.0.\n");
    if let Some(defs) = schema["$defs"].as_object() {
        for (name, value) in defs {
            types.push_str(&format!(
                "export type {name} = {}\n",
                crate::artifacts::luau(value)
            ));
        }
    }
    types.push_str(&format!(
        "export type State = {}\nreturn {{}}\n",
        crate::artifacts::luau(&schema)
    ));
    let frames = [
        json!({"t":"sub","topics":[TOPIC]}),
        json!({"t":"snap","topic":TOPIC,"seq":0,"data":{"enabled":false,"ready":false,"status":"disabled","location":null,"asset":null}}),
        json!({"t":"snap","topic":TOPIC,"seq":1,"data":{"enabled":true,"ready":true,"status":"ready","location":{"city":"Harbour","latitude":60.0,"longitude":5.0},"asset":{"path":"/private/cache/nacre/daemon-weather-photo/city.image","checked":1800000000.0,"author":"Fixture artist","license":"CC BY-SA 4.0","source":"https://commons.wikimedia.org/wiki/File:Harbour.jpg"}}}),
        json!({"t":"unsub","topics":[TOPIC]}),
    ];
    BTreeMap::from([
        (
            "protocol/schema/weather-photo-state.json".into(),
            serde_json::to_string_pretty(&schema).expect("schema") + "\n",
        ),
        ("protocol/luau/weather-photo.d.luau".into(), types),
        (
            "protocol/fixtures/weather-photo.jsonl".into(),
            frames
                .iter()
                .map(|f| serde_json::to_string(f).expect("fixture") + "\n")
                .collect(),
        ),
    ])
}
