fn encode(frames: &[Value]) -> String {
    frames
        .iter()
        .map(|frame| {
            let bytes = serde_json::to_vec(frame).expect("finite core fixture");
            crate::framing::decode(&bytes).expect("bounded core fixture");
            String::from_utf8(bytes).expect("JSON UTF8") + "\n"
        })
        .collect()
}
