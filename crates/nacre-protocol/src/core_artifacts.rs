//! Separate exports keep the original wire transcripts byte-for-byte unchanged.
use crate::core_services::{CoreCall, CoreResult, CoreSnapshot};
use serde_json::{json, Value};
use std::collections::BTreeMap;

pub(crate) fn generate() -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let mut definitions = BTreeMap::new();
    let mut roots = Vec::new();
    for (name, filename, schema) in [
        (
            "CoreCall",
            "core-service-call",
            schemars::schema_for!(CoreCall),
        ),
        (
            "CoreResult",
            "core-service-result",
            schemars::schema_for!(CoreResult),
        ),
        (
            "CoreSnapshot",
            "core-service-state",
            schemars::schema_for!(CoreSnapshot),
        ),
    ] {
        let value = serde_json::to_value(schema).expect("finite service schema");
        if let Some(defs) = value.get("$defs").and_then(Value::as_object) {
            for (key, definition) in defs {
                if let Some(previous) = definitions.insert(key.clone(), definition.clone()) {
                    assert_eq!(previous, *definition, "Inconsistent shared type {key}");
                }
            }
        }
        roots.push((name, value.clone()));
        out.insert(
            format!("protocol/schema/{filename}.json"),
            serde_json::to_string_pretty(&value).expect("schema JSON") + "\n",
        );
    }
    let mut luau = String::from("-- Generated by nacre-protocol; do not edit. GPL-3.0-only.\n-- Reserved contracts only; inspect welcome before using a service.\n");
    for (name, schema) in definitions {
        luau.push_str(&format!(
            "export type {name} = {}\n",
            crate::artifacts::luau(&schema)
        ));
    }
    for (name, schema) in roots {
        luau.push_str(&format!(
            "export type {name} = {}\n",
            crate::artifacts::luau(&schema)
        ));
    }
    luau.push_str("return {}\n");
    out.insert("protocol/luau/core-services.d.luau".into(), luau);
    out.extend(transcripts());
    out
}

fn entities(value: Value) -> Value {
    let order = value
        .as_object()
        .expect("fixture entities")
        .keys()
        .cloned()
        .collect::<Vec<_>>();
    json!({"items":value,"order":order})
}

