//! Semantic status-pill controls that do not expose implementation identifiers.
use crate::{Capability, ErrorCode, Failure, Method};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::collections::BTreeMap;

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct VolumeAdjust {
    /// Relative change in normalized volume, from -0.20 through +0.20.
    #[schemars(range(min = -0.2, max = 0.2))]
    pub delta: f64,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum VolumeDirection {
    Up,
    Down,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct VolumeStep {
    pub direction: VolumeDirection,
    #[serde(default)]
    pub key_ms: Option<u64>,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct PillEmpty {}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct BluetoothEnabled {
    pub enabled: bool,
}

// `bluetooth.set_power` remains reserved for adapter-addressed control. The
// status pill has only the system default controller, so this action deliberately
// carries no opaque BlueZ adapter identifier.

impl VolumeAdjust {
    pub fn validate(&self) -> Result<(), Failure> {
        if self.delta.is_finite() && (-0.2..=0.2).contains(&self.delta) {
            Ok(())
        } else {
            Err(invalid())
        }
    }
}
fn invalid() -> Failure {
    Failure::new(ErrorCode::Validation, "Invalid status pill action", false).dispatch_state(false)
}

pub fn methods() -> BTreeMap<String, Method> {
    [
        ("audio.adjust_volume", schemars::schema_for!(VolumeAdjust), Capability::System),
        ("audio.step", schemars::schema_for!(VolumeStep), Capability::System),
        ("audio.toggle_mute", schemars::schema_for!(PillEmpty), Capability::System),
        ("bluetooth.set_enabled", schemars::schema_for!(BluetoothEnabled), Capability::System),
    ]
    .into_iter()
    .map(|(name, schema, class)| (name.into(), Method {
        v: 1,
        class,
        timeout: 10_000,
        params: serde_json::to_value(schema).expect("pill control schema"),
        result: json!({"type":"object","properties":{"changed":{"type":"boolean"}},"required":["changed"],"additionalProperties":false}),
    }))
    .collect()
}

pub(crate) fn exports() -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    let mut types =
        String::from("-- Generated by nacre-protocol; do not edit. MIT OR Apache-2.0.\n");
    for (name, file, schema) in [
        (
            "VolumeAdjust",
            "volume-adjust",
            schemars::schema_for!(VolumeAdjust),
        ),
        ("PillEmpty", "pill-empty", schemars::schema_for!(PillEmpty)),
        (
            "VolumeDirection",
            "volume-direction",
            schemars::schema_for!(VolumeDirection),
        ),
        (
            "VolumeStep",
            "volume-step",
            schemars::schema_for!(VolumeStep),
        ),
        (
            "BluetoothEnabled",
            "bluetooth-enabled",
            schemars::schema_for!(BluetoothEnabled),
        ),
    ] {
        let schema = serde_json::to_value(schema).expect("pill control schema");
        types.push_str(&format!(
            "export type {name} = {}\n",
            crate::artifacts::luau(&schema)
        ));
        files.insert(
            format!("protocol/schema/{file}.json"),
            serde_json::to_string_pretty(&schema).expect("schema JSON") + "\n",
        );
    }
    types.push_str("return {}\n");
    files.insert("protocol/luau/pill-controls.d.luau".into(), types);
    let frames = [
        json!({"t":"call","id":411,"m":"audio.adjust_volume","p":{"delta":0.05}}),
        json!({"t":"ret","id":411,"ok":{"changed":true}}),
        json!({"t":"call","id":414,"m":"audio.step","p":{"direction":"up","key_ms":1782450000000_u64}}),
        json!({"t":"ret","id":414,"ok":{"changed":true}}),
        json!({"t":"call","id":412,"m":"audio.toggle_mute","p":{}}),
        json!({"t":"ret","id":412,"ok":{"changed":true}}),
        json!({"t":"call","id":413,"m":"bluetooth.set_enabled","p":{"enabled":false}}),
        json!({"t":"ret","id":413,"ok":{"changed":true}}),
    ];
    files.insert(
        "protocol/fixtures/pill-controls.jsonl".into(),
        frames
            .iter()
            .map(|frame| serde_json::to_string(frame).expect("pill control transcript") + "\n")
            .collect(),
    );
    files
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn volume_adjust_is_finite_and_bounded() {
        assert!(VolumeAdjust { delta: 0.2 }.validate().is_ok());
        assert!(VolumeAdjust { delta: -0.2 }.validate().is_ok());
        assert!(VolumeAdjust { delta: 0.0 }.validate().is_ok());
        assert!(VolumeAdjust { delta: f64::NAN }.validate().is_err());
        assert!(VolumeAdjust { delta: 0.21 }.validate().is_err());
    }
    #[test]
    fn methods_are_semantic_and_inputs_reject_unknown_fields() {
        assert_eq!(methods().len(), 4);
        assert!(
            serde_json::from_value::<VolumeAdjust>(json!({"delta":0.1,"node":"arbitrary"}))
                .is_err()
        );
        assert!(serde_json::from_value::<PillEmpty>(json!({"anything":true})).is_err());
    }
}
