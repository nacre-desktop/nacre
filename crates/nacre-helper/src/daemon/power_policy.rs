//! User-session idle and hardware power policy generated from power.json.
use super::hub::Shared;
use crate::{paths::Paths, Result};
use serde_json::Value;
use std::{fs, path::Path, time::Duration};
use tokio::sync::broadcast::error::RecvError;

fn minutes(data: &Value, key: &str) -> u64 {
    super::settings_validation::power_idle_minutes(data, key)
}

fn valid(data: &Value) -> bool {
    super::settings_validation::power_idle_valid(data)
}

fn policy(data: &Value) -> Value {
    serde_json::json!({
        "idle": {"dim": minutes(data, "dim"), "sleep": minutes(data, "sleep")},
        "lid": data["lid"].as_str().unwrap_or("suspend"),
        "button": data["button"].as_str().unwrap_or("lock")
    })
}

fn quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

fn idle_listeners(data: &Value, helper: &Path) -> String {
    let dim = minutes(data, "dim");
    let sleep = minutes(data, "sleep");
    let mut text = String::new();
    if dim > 0 {
        text.push_str(&format!(
            "\nlistener {{\n    timeout = {}\n    on-timeout = {} idle-brightness dim\n    on-resume = {} idle-brightness restore\n}}\n",
            dim * 60,
            quote(&helper.to_string_lossy()),
            quote(&helper.to_string_lossy())
        ));
    }
    if sleep > 0 {
        text.push_str(&format!(
            "\nlistener {{\n    timeout = {}\n    on-timeout = systemctl suspend\n}}\n",
            sleep * 60
        ));
    }
    text
}

/// The power menu cannot open over the lock screen; a locked press suspends instead.
const MENU: &str =
    "if pidof hyprlock >/dev/null; then systemctl suspend; else nacrectl ui nacre menu power ''; fi";

fn shell_action(action: &str) -> &'static str {
    match action {
        "suspend" => "systemctl suspend",
        "lock" => "loginctl lock-session",
        "menu" => MENU,
        _ => "true",
    }
}

/// Lid "suspend" stays with logind, whose HandleLidSwitchDocked keeps a docked
/// laptop awake; the compositor acts on the lid only for "lock".
fn lid_action(data: &Value) -> &'static str {
    match data["lid"].as_str() {
        Some("lock") => "lock",
        _ => "nothing",
    }
}

fn power_lua(data: &Value) -> String {
    let button = data["button"].as_str().unwrap_or("lock");
    // Hyprland switch binds match libinput device names; "Lid Switch" is the ACPI lid name.
    format!(
        "-- Generated by Nacre from power.json.\nhl.unbind(\"XF86PowerOff\")\nhl.unbind(\"switch:on:Lid Switch\")\nhl.bind(\"XF86PowerOff\", hl.dsp.exec_cmd({:?}), {{ description=\"Nacre:power-button\", locked=true }})\nhl.bind(\"switch:on:Lid Switch\", hl.dsp.exec_cmd({:?}), {{ locked=true }})\n",
        shell_action(button), shell_action(lid_action(data))
    )
}

fn niri_spawn(action: &str) -> String {
    match action {
        "suspend" => "spawn \"systemctl\" \"suspend\"".into(),
        "lock" => "spawn \"loginctl\" \"lock-session\"".into(),
        "menu" => format!("spawn-sh {}", Value::from(MENU)),
        _ => "spawn \"true\"".into(),
    }
}

/// `niri_policy(&json!({}))` is the safe default seeded before the daemon runs.
pub(crate) fn niri_policy(data: &Value) -> String {
    let button = data["button"].as_str().unwrap_or("lock");
    format!(
        "// Generated by Nacre from power.json.\nbinds {{\n    XF86PowerOff repeat=false allow-when-locked=true hotkey-overlay-title=\"Nacre:power-button\" {{ {}; }}\n}}\nswitch-events {{\n    lid-close {{ {}; }}\n}}\n",
        niri_spawn(button),
        niri_spawn(lid_action(data))
    )
}

fn write_if_changed(path: &Path, text: &str) -> Result<bool> {
    if fs::read(path).ok().as_deref() == Some(text.as_bytes()) {
        return Ok(false);
    }
    crate::files::atomic(path, text.as_bytes())?;
    Ok(true)
}

/// Returns whether the idle listeners and whether the compositor bindings changed.
fn write_policy(paths: &Paths, data: &Value) -> Result<(bool, bool)> {
    if !valid(data) {
        return Err("Invalid idle policy: dim must be below sleep".into());
    }
    let listeners = idle_listeners(data, &paths.tools().join("nacre-helper"));
    let idle = write_if_changed(&paths.config.join("power-idle.conf"), &listeners)?;
    let hyprland = write_if_changed(&paths.config.join("power.lua"), &power_lua(data))?;
    let niri = write_if_changed(
        &paths.config.join("niri/power-policy.kdl"),
        &niri_policy(data),
    )?;
    Ok((idle, hyprland || niri))
}

/// Whether the compositor config on disk loads Nacre's power policy. After an upgrade
/// the include only appears at the next session start; until then a reload would keep
/// the old bindings, so lid and button actions must not be offered or held.
pub(crate) fn policy_included(
    paths: &Paths,
    backend: &str,
    env: &std::collections::BTreeMap<String, String>,
) -> bool {
    match backend {
        "niri" => crate::compositor::niri_config_includes(
            paths,
            env,
            &paths.config.join("niri/power-policy.kdl"),
        ),
        "hyprland" => fs::read_to_string(paths.home.join(".config/hypr/hyprland.lua"))
            .is_ok_and(|text| text.contains("load_private(\"power\")")),
        _ => false,
    }
}

fn systemctl(verb: &str, unit: &str) -> Result<()> {
    crate::process::checked(
        "systemctl",
        &["--user".into(), verb.into(), unit.into()],
        None,
        Duration::from_secs(5),
    )?;
    Ok(())
}

/// Writes the policy and returns whether the compositor must reload its bindings.
fn apply(paths: &Paths, data: &Value, backend: &str) -> Result<bool> {
    apply_with(paths, data, backend, systemctl)
}

fn apply_with(
    paths: &Paths,
    data: &Value,
    backend: &str,
    mut service: impl FnMut(&str, &str) -> Result<()>,
) -> Result<bool> {
    let (idle_changed, compositor_changed) = write_policy(paths, data)?;
    // hyprlock runs inside the idle unit's cgroup: restart only when its config
    // changed, or every power edit (and daemon start) would kill an active lock screen.
    if idle_changed {
        let packaged_niri_lock = paths
            .home
            .join(".config/systemd/user/nacre-niri-lock.service")
            .is_file();
        let idle_service = if backend == "niri" && packaged_niri_lock {
            "nacre-niri-lock.service"
        } else {
            "hypridle.service"
        };
        // Only an idle daemon systemd runs is restarted: an `exec-once hypridle` copy is
        // not a unit, and starting the unit beside it would double the lock/suspend listeners.
        if service("is-active", idle_service).is_err() {
            tracing::info!(
                idle_service,
                "Idle daemon is not a running user unit; new idle times apply at next login"
            );
        } else if let Err(error) = service("restart", idle_service) {
            tracing::warn!(%error, idle_service, "Idle service did not restart cleanly");
            // Never leave the session able to suspend without its lock hook.
            if let Err(error) = service("start", idle_service) {
                tracing::warn!(%error, idle_service, "Idle service is not running");
            }
        }
    }
    Ok(compositor_changed)
}

async fn inhibit_lid(system: &zbus::Connection) -> Result<zbus::zvariant::OwnedFd> {
    let proxy = zbus::Proxy::new(
        system,
        "org.freedesktop.login1",
        "/org/freedesktop/login1",
        "org.freedesktop.login1.Manager",
    )
    .await?;
    Ok(proxy
        .call(
            "Inhibit",
            &(
                "handle-lid-switch",
                "Nacre",
                "The lid action is set to lock or nothing",
                "block",
            ),
        )
        .await?)
}

pub async fn run(hub: Shared, paths: Paths) -> Result<()> {
    let mut notices = hub.borrow().observe();
    let system = zbus::Connection::system().await?;
    let mut last_applied: Option<Value> = None;
    let mut lid_inhibitor = None;
    loop {
        let data = hub
            .borrow()
            .snapshot("settings.store.power")
            .and_then(|snapshot| snapshot.get("data").cloned())
            .unwrap_or_else(|| serde_json::json!({}));
        let next = policy(&data);
        if last_applied.as_ref() != Some(&next) {
            let environment: std::collections::BTreeMap<_, _> = std::env::vars().collect();
            let backend = crate::compositor::backend::select(&environment)
                .unwrap_or("hyprland")
                .to_owned();
            let included = policy_included(&paths, &backend, &environment);
            let apply_paths = paths.clone();
            let apply_data = data.clone();
            let applied = tokio::task::spawn_blocking(move || {
                if let Err(error) = crate::idle_brightness::restore(&apply_paths) {
                    tracing::warn!(%error, "Could not restore every dimmed display before updating idle policy");
                }
                apply(&apply_paths, &apply_data, &backend)
            })
            .await?;
            match applied {
                Err(error) => tracing::warn!(%error, "Power settings could not be applied"),
                Ok(reload) => {
                    last_applied = Some(next);
                    let control = { hub.borrow().compositor.clone() };
                    let mut bindings_ready = control.is_some() && included;
                    if let (true, Some(control)) = (reload, control) {
                        if let Err(error) = control
                            .with(|backend| {
                                backend.action("reload", &[], &serde_json::json!({"timeout":5}))?;
                                Ok(())
                            })
                            .await
                        {
                            bindings_ready = false;
                            tracing::warn!(%error, "Compositor did not reload power bindings");
                        }
                    }
                    // Taken after the bindings are live, released when logind owns the lid again.
                    let hold = matches!(data["lid"].as_str(), Some("lock" | "nothing"));
                    if !hold {
                        lid_inhibitor = None;
                    } else if bindings_ready && lid_inhibitor.is_none() {
                        match inhibit_lid(&system).await {
                            Ok(lock) => lid_inhibitor = Some(lock),
                            Err(error) => {
                                tracing::warn!(%error, "logind kept the lid switch; closing the lid suspends")
                            }
                        }
                    }
                }
            }
        }
        loop {
            match notices.recv().await {
                Ok(super::hub::Notice::Changed { topic, .. })
                    if topic == "settings.store.power" =>
                {
                    break
                }
                Ok(_) => {}
                Err(RecvError::Lagged(_)) => break,
                Err(RecvError::Closed) => return Err("Power settings observer ended".into()),
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn idle_values_generate_dim_then_sleep_and_zero_never() {
        let text = idle_listeners(
            &json!({"idle":{"dim":5.0,"sleep":30.0}}),
            std::path::Path::new("/home/test/.local/share/nacre/shell/tools/nacre-helper"),
        );
        assert!(text.contains("timeout = 300\n    on-timeout = '/home/test/.local/share/nacre/shell/tools/nacre-helper' idle-brightness dim"));
        assert!(text.contains("timeout = 1800\n    on-timeout = systemctl suspend"));
        assert_eq!(
            idle_listeners(
                &json!({"idle":{"dim":0,"sleep":0}}),
                std::path::Path::new("/bin/nacre-helper")
            )
            .matches("listener {")
            .count(),
            0
        );
    }

    #[test]
    fn dim_must_precede_sleep_when_both_are_enabled() {
        assert!(valid(&json!({"idle":{"dim":0,"sleep":2}})));
        assert!(valid(&json!({"idle":{"dim":1,"sleep":2}})));
        assert!(!valid(&json!({"idle":{"dim":2,"sleep":2}})));
        assert!(!valid(&json!({"idle":{"dim":3,"sleep":2}})));
    }

    #[test]
    fn power_actions_are_generated_for_both_compositors() {
        // Lid "suspend" is logind's (HandleLidSwitchDocked), so the compositor only acts on "lock".
        for (lid, lid_shell, lid_niri) in [
            ("suspend", "true", "spawn \"true\""),
            (
                "lock",
                "loginctl lock-session",
                "spawn \"loginctl\" \"lock-session\"",
            ),
            ("nothing", "true", "spawn \"true\""),
        ] {
            for (button, button_command) in [
                ("lock", "loginctl lock-session"),
                ("suspend", "systemctl suspend"),
                ("menu", "if pidof hyprlock >/dev/null; then systemctl suspend; else nacrectl ui nacre menu power ''; fi"),
            ] {
                let data = json!({"lid":lid,"button":button});
                let hyprland = power_lua(&data);
                let niri = niri_policy(&data);
                assert!(hyprland.contains(&format!(
                    "hl.bind(\"switch:on:Lid Switch\", hl.dsp.exec_cmd({lid_shell:?})"
                )));
                assert!(hyprland.contains(&format!(
                    "hl.bind(\"XF86PowerOff\", hl.dsp.exec_cmd({button_command:?})"
                )));
                assert!(niri.contains("allow-when-locked=true"));
                assert!(niri.contains(&format!("lid-close {{ {lid_niri}; }}")));
                if button == "menu" {
                    assert!(niri.contains(&format!("{{ spawn-sh {button_command:?}; }}")));
                } else {
                    assert!(niri.contains(&niri_spawn(button)));
                }
            }
        }
        assert_eq!(
            niri_policy(&json!({})),
            niri_policy(&json!({"lid":"suspend","button":"lock"}))
        );
    }

    #[test]
    fn failed_idle_restart_recovers_and_still_reloads_bindings() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::new(home.path());
        let data = json!({"lid":"lock","idle":{"dim":1,"sleep":2}});
        let mut calls = Vec::new();
        assert!(apply_with(&paths, &data, "hyprland", |verb, unit| {
            calls.push((verb.to_owned(), unit.to_owned()));
            Err("fixture failure".into())
        })
        .unwrap());
        // Not a running user unit (e.g. `exec-once hypridle`): systemd must not start a second one.
        assert_eq!(
            calls,
            [("is-active".to_owned(), "hypridle.service".to_owned())]
        );
        assert!(!apply_with(&paths, &data, "hyprland", |_, _| panic!(
            "unchanged idle service"
        ))
        .unwrap());
    }

    #[test]
    fn a_running_idle_unit_restarts_and_recovers_when_restart_fails() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::new(home.path());
        let data = json!({"idle":{"dim":1,"sleep":2}});
        let mut calls = Vec::new();
        apply_with(&paths, &data, "hyprland", |verb, unit| {
            calls.push((verb.to_owned(), unit.to_owned()));
            if verb == "is-active" {
                Ok(())
            } else {
                Err("fixture failure".into())
            }
        })
        .unwrap();
        let verbs: Vec<_> = calls.iter().map(|(verb, _)| verb.as_str()).collect();
        assert_eq!(verbs, ["is-active", "restart", "start"]);
    }

    #[test]
    fn hardware_actions_wait_for_the_session_to_include_the_policy() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::new(home.path());
        let env = std::collections::BTreeMap::new();
        let hypr = home.path().join(".config/hypr/hyprland.lua");
        fs::create_dir_all(hypr.parent().unwrap()).unwrap();
        fs::write(&hypr, "load_private(\"host\")\n").unwrap();
        assert!(!policy_included(&paths, "hyprland", &env));
        fs::write(&hypr, "load_private(\"power\")\nload_private(\"host\")\n").unwrap();
        assert!(policy_included(&paths, "hyprland", &env));

        let policy = paths.config.join("niri/power-policy.kdl");
        fs::create_dir_all(policy.parent().unwrap()).unwrap();
        fs::write(&policy, niri_policy(&json!({}))).unwrap();
        let root = home.path().join("session/config.kdl");
        fs::create_dir_all(root.parent().unwrap()).unwrap();
        fs::write(&root, "binds {\n}\n").unwrap();
        let env = std::collections::BTreeMap::from([(
            "NIRI_CONFIG".to_owned(),
            root.to_string_lossy().into_owned(),
        )]);
        assert!(!policy_included(&paths, "niri", &env));
        fs::write(
            &root,
            format!("include \"{}\"\nbinds {{\n}}\n", policy.display()),
        )
        .unwrap();
        assert!(policy_included(&paths, "niri", &env));
    }

    #[test]
    fn unchanged_policy_is_not_rewritten() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::new(home.path());
        let settings = json!({"idle":{"dim":5,"sleep":30},"lid":"lock","button":"suspend"});
        assert_eq!(write_policy(&paths, &settings).unwrap(), (true, true));
        assert_eq!(write_policy(&paths, &settings).unwrap(), (false, false));
        let lid = json!({"idle":{"dim":5,"sleep":30},"lid":"nothing","button":"suspend"});
        assert_eq!(write_policy(&paths, &lid).unwrap(), (false, true));
        let idle = json!({"idle":{"dim":1,"sleep":30},"lid":"nothing","button":"suspend"});
        assert_eq!(write_policy(&paths, &idle).unwrap(), (true, false));
    }

    #[test]
    fn generated_policy_keeps_private_idle_and_compositor_configs_unchanged() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::new(home.path());
        fs::create_dir_all(&paths.config).unwrap();
        let private_idle = paths.config.join("hypridle.local.conf");
        fs::write(&private_idle, "# private\nlistener { timeout = 901 }\n").unwrap();
        let niri_idle = paths.config.join("niri/hypridle.conf");
        fs::create_dir_all(niri_idle.parent().unwrap()).unwrap();
        fs::write(&niri_idle, "general { lock_cmd = custom-lock }\n").unwrap();
        let settings = json!({"idle":{"dim":5,"sleep":30},"lid":"lock","button":"suspend"});
        write_policy(&paths, &settings).unwrap();
        assert_eq!(
            fs::read_to_string(private_idle).unwrap(),
            "# private\nlistener { timeout = 901 }\n"
        );
        assert_eq!(
            fs::read_to_string(niri_idle).unwrap(),
            "general { lock_cmd = custom-lock }\n"
        );
        assert!(fs::read_to_string(paths.config.join("power-idle.conf"))
            .unwrap()
            .contains("timeout = 300"));
        assert!(fs::read_to_string(paths.config.join("power.lua"))
            .unwrap()
            .contains("systemctl suspend"));
        assert!(
            fs::read_to_string(paths.config.join("niri/power-policy.kdl"))
                .unwrap()
                .contains("spawn \"loginctl\" \"lock-session\"")
        );
    }

    #[test]
    fn niri_generated_policy_validates_when_niri_is_available() {
        if crate::process::run("niri", &["--version".into()], None, Duration::from_secs(2)).is_err()
        {
            return;
        }
        let folder = tempfile::tempdir().unwrap();
        let config = folder.path().join("power-policy.kdl");
        for lid in ["suspend", "lock", "nothing"] {
            for button in ["lock", "suspend", "menu"] {
                fs::write(&config, niri_policy(&json!({"lid":lid,"button":button}))).unwrap();
                crate::process::checked(
                    "niri",
                    &[
                        "validate".into(),
                        "-c".into(),
                        config.to_string_lossy().into_owned(),
                    ],
                    None,
                    Duration::from_secs(5),
                )
                .unwrap();
            }
        }
    }
}
