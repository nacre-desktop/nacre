struct Rng(u64);
impl Rng {
    fn next(&mut self, n: usize) -> usize {
        self.0 = self
            .0
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        ((self.0 >> 33) as usize) % n
    }
}
struct Fixture {
    /// (relative path, family key, tags, archived)
    notes: Vec<(String, &'static str, Vec<&'static str>, bool)>,
}
fn day(rng: &mut Rng) -> String {
    let d = rng.next(97);
    let (m, d) = if d < 31 {
        (8, d + 1)
    } else if d < 61 {
        (9, d - 30)
    } else {
        (10, d - 60)
    };
    format!("2026-{m:02}-{d:02}T{:02}:00:00+00:00", rng.next(24))
}
/// Dated title slug, like `nacre-brain note` file names.
fn slug(i: usize, title: &str) -> String {
    let words: Vec<String> = title
        .to_lowercase()
        .split(|c: char| !c.is_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(str::to_owned)
        .collect();
    format!(
        "2026{i:05}-{}",
        words.join("-").chars().take(48).collect::<String>()
    )
}
fn write(root: &Path, rel: &str, body: &str) {
    let path = root.join(rel);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, body).unwrap();
}
fn fixture(root: &Path) -> Fixture {
    let mut rng = Rng(42);
    let mut notes = Vec::new();
    for family in FAMILIES {
        for i in 0..family.count {
            let (title, body, tags) = family.templates[i % family.templates.len()];
            let n = format!("{}", 100 + i * 7);
            let v = VENUES[rng.next(VENUES.len())];
            let (mut title, mut tags) = (title.replace("{n}", &n).replace("{v}", v), tags.to_vec());
            if family.key == "orient" && i == 0 {
                title = EXACT.into();
                tags = vec!["exact", "palette"];
            }
            let archived = i % 8 == 7;
            let folder = FOLDERS[rng.next(FOLDERS.len())];
            let name = slug(notes.len(), &title);
            let rel = if archived {
                format!("archive/{folder}/2026-09/{name}.md")
            } else {
                format!("{folder}/{name}.md")
            };
            let filler: Vec<&str> = (0..12).map(|_| FILLER[rng.next(FILLER.len())]).collect();
            let text = format!(
                "# {title}\nRecorded: {}\nConfidence: verified\nWorlds: {}\nAreas: {}\nSource: synthetic fixture\n\n{}\n\nAlso touched {}.\n",
                day(&mut rng), family.worlds, family.areas, body.replace("{n}", &n).replace("{v}", v), filler.join(" ")
            );
            write(root, &rel, &text);
            notes.push((rel, family.key, tags, archived));
        }
    }
    while notes.len() < 2000 {
        let (world, area) = DISTRACTOR_WORLDS[rng.next(DISTRACTOR_WORLDS.len())];
        let words: Vec<&str> = (0..40).map(|_| FILLER[rng.next(FILLER.len())]).collect();
        let mut body = String::new();
        for chunk in words.chunks(8) {
            body += &format!(
                "{} {}. ",
                chunk.join(" "),
                CONFUSABLE[rng.next(CONFUSABLE.len())]
            );
        }
        let archived = rng.next(10) == 0;
        let folder = [
            "checkpoints",
            "checkpoints",
            "checkpoints",
            "inbox",
            "runbooks",
            "decisions",
            "projects",
        ][rng.next(7)];
        let title = format!("Checkpoint: {} {} {}", words[0], words[1], words[2]);
        let name = slug(notes.len(), &title);
        let rel = if archived {
            format!("archive/{folder}/2026-08/{name}.md")
        } else {
            format!("{folder}/{name}.md")
        };
        let areas = if area.is_empty() {
            String::new()
        } else {
            format!("Areas: {area}\n")
        };
        let text = format!(
            "# {title}\nRecorded: {}\nConfidence: reported\nWorlds: {world}\n{areas}\n{body}\n",
            day(&mut rng)
        );
        write(root, &rel, &text);
        notes.push((rel, "distractor", vec![], archived));
    }
    Fixture { notes }
}
