fn relevant(fx: &Fixture, family: &str, tag: &str) -> Vec<String> {
    fx.notes
        .iter()
        .filter(|(_, f, tags, archived)| {
            !archived && (*f == family || family == "*") && (tag.is_empty() || tags.contains(&tag))
        })
        .map(|n| n.0.clone())
        .collect()
}
/// recall@5 (capped by the relevant count) and reciprocal rank of one query.
fn score(ranked: &[String], relevant: &[String]) -> (f64, f64) {
    if relevant.is_empty() {
        let hit = f64::from(u8::from(ranked.is_empty()));
        return (hit, hit);
    }
    let found = ranked
        .iter()
        .take(5)
        .filter(|p| relevant.contains(p))
        .count();
    let rr = ranked
        .iter()
        .position(|p| relevant.contains(p))
        .map_or(0.0, |i| 1.0 / (i + 1) as f64);
    (found as f64 / relevant.len().min(5) as f64, rr)
}
/// The pre-N0142 viewer engine: casefolded substring AND over path + text,
/// shown newest first; archive hidden like the viewer's default.
fn old_viewer(root: &Path, fx: &Fixture, query: &str) -> Vec<String> {
    let words: Vec<String> = query
        .to_lowercase()
        .split_whitespace()
        .map(str::to_owned)
        .collect();
    let mut hits: Vec<(String, String)> = fx
        .notes
        .iter()
        .filter(|n| !n.3)
        .filter_map(|n| {
            let text = fs::read_to_string(root.join(&n.0)).unwrap();
            let content = format!("{}\n{}", n.0, text).to_lowercase();
            words.iter().all(|w| content.contains(w)).then(|| {
                let recorded = text
                    .lines()
                    .find_map(|l| l.strip_prefix("Recorded: "))
                    .unwrap_or("")
                    .to_owned();
                (recorded, n.0.clone())
            })
        })
        .collect();
    hits.sort_by(|a, b| b.0.cmp(&a.0));
    hits.into_iter().map(|h| h.1).collect()
}
/// The pre-N0142 CLI engine: `rg -n -i -F QUERY` (literal phrase), path order.
fn old_cli(root: &Path, fx: &Fixture, query: &str) -> Vec<String> {
    let phrase = query.to_lowercase();
    let mut hits: Vec<String> = fx
        .notes
        .iter()
        .filter(|n| {
            !n.3 && fs::read_to_string(root.join(&n.0))
                .unwrap()
                .to_lowercase()
                .contains(&phrase)
        })
        .map(|n| n.0.clone())
        .collect();
    hits.sort();
    hits
}
fn ranked(root: &Path, query: &str) -> (Vec<String>, serde_json::Value) {
    let value = search(
        root,
        query,
        &Options {
            limit: 50,
            ..Options::default()
        },
    )
    .unwrap();
    let paths = value["results"]
        .as_array()
        .unwrap()
        .iter()
        .map(|r| r["path"].as_str().unwrap().to_owned())
        .collect();
    (paths, value)
}

#[test]
fn search_quality_gate_on_2000_synthetic_notes() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    let fx = fixture(root);
    assert_eq!(fx.notes.len(), 2000);
    invalidate();
    let mut totals = [[0.0f64; 2]; 3];
    println!("| query | old viewer rank | old CLI rank | new rank | new top result |");
    println!("| --- | --- | --- | --- | --- |");
    for (query, family, tag) in QUERIES {
        let rel = relevant(&fx, family, tag);
        let (new, value) = ranked(root, query);
        let runs = [
            old_viewer(root, &fx, query),
            old_cli(root, &fx, query),
            new.clone(),
        ];
        let mut ranks = Vec::new();
        for (engine, list) in runs.iter().enumerate() {
            let (recall, rr) = score(list, &rel);
            totals[engine][0] += recall;
            totals[engine][1] += rr;
            ranks.push(if rr > 0.0 {
                format!("{:.0}", 1.0 / rr)
            } else {
                "-".into()
            });
        }
        let top = value["results"][0]["title"].as_str().unwrap_or("(none)");
        println!(
            "| {query} | {} | {} | {} | {top} |",
            ranks[0], ranks[1], ranks[2]
        );
        if *query == "smash card" {
            assert!(
                rel.contains(&new[0]),
                "smash card must rank a Smash-Board note first"
            );
        }
        if *query == "tailscail" {
            assert_eq!(value["didYouMean"], "tailscale");
        }
    }
    let n = QUERIES.len() as f64;
    let [viewer, cli, new] = totals.map(|[r, m]| (r / n, m / n));
    println!("old viewer recall@5 {:.3} MRR {:.3}", viewer.0, viewer.1);
    println!("old CLI    recall@5 {:.3} MRR {:.3}", cli.0, cli.1);
    println!("new        recall@5 {:.3} MRR {:.3}", new.0, new.1);
    assert!(new.0 >= 0.9, "recall@5 {:.3} below 0.9", new.0);
    assert!(new.1 >= 0.75, "MRR {:.3} below 0.75", new.1);
}

#[test]
#[ignore = "latency gate: run with --release --ignored on the build host"]
fn search_latency_gate_on_2000_synthetic_notes() {
    let dir = tempfile::tempdir().unwrap();
    let keep = std::env::var_os("NACRE_SEARCH_EVAL_DIR").map(std::path::PathBuf::from);
    let root = keep.as_deref().unwrap_or(dir.path());
    fixture(root);
    let _ = fs::remove_file(root.join(".brain-state/index/search.json"));
    let rss = || {
        fs::read_to_string("/proc/self/status")
            .unwrap()
            .lines()
            .find_map(|l| {
                l.strip_prefix("VmRSS:")
                    .map(|v| v.trim().trim_end_matches(" kB").parse::<f64>().unwrap() / 1024.0)
            })
            .unwrap()
    };
    let before = rss();
    invalidate();
    let start = Instant::now();
    ranked(root, "warm up");
    let cold = start.elapsed();
    invalidate();
    let start = Instant::now();
    ranked(root, "warm up");
    let restat = start.elapsed();
    let build = (
        cold.as_secs_f64() * 1000.0,
        restat.as_secs_f64() * 1000.0,
        rss() - before,
    );
    println!(
        "cold build {:.1} ms, unchanged re-stat {:.1} ms, index RSS +{:.1} MiB",
        build.0, build.1, build.2
    );
    // CLI default (20 results) and the viewer's request size (200 results).
    for limit in [20, 200] {
        let mut times = Vec::new();
        for _ in 0..20 {
            for (query, _, _) in QUERIES {
                let start = Instant::now();
                search(
                    root,
                    query,
                    &Options {
                        limit,
                        ..Options::default()
                    },
                )
                .unwrap();
                times.push(start.elapsed().as_secs_f64() * 1000.0);
            }
        }
        times.sort_by(f64::total_cmp);
        let p = |q: f64| times[((times.len() as f64 - 1.0) * q) as usize];
        println!(
            "limit {limit}: warm p50 {:.2} ms p95 {:.2} ms max {:.2} ms ({} queries)",
            p(0.5),
            p(0.95),
            times[times.len() - 1],
            times.len()
        );
        assert!(p(0.95) < 50.0, "warm p95 {:.2} ms", p(0.95));
    }
}
