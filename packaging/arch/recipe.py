#!/usr/bin/env python3
"""Render a conventional PKGBUILD from the single distro dependency mapping."""

import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]


def array(values):
    return "(" + " ".join("'" + value + "'" for value in values) + ")"


def render(root, revision, sequence=None):
    mapping = json.loads((root / "packaging/packages.json").read_text())["arch"]
    lock = json.loads((root / "dependencies.lock.json").read_text())["orient"]
    version = (root / "VERSION").read_text().strip().replace("-dev.", "dev")
    if "-dev." in (root / "VERSION").read_text() and sequence is not None:
        version += ".r" + str(sequence) + ".g" + revision[:12]
    sources = [
        f"nacre::git+https://github.com/nacre-desktop/nacre.git#commit={revision}",
        f"orient::git+https://github.com/nacre-desktop/orient.git#commit={lock['revision']}",
    ]
    checksums = ["SKIP", "SKIP"]
    core_licenses = ["GPL-3.0-only"]
    for group in json.loads((root / "nacre/shell-tools/font-assets.json").read_text())[
        "groups"
    ]:
        if group["default"]:
            if group["license"] not in core_licenses:
                core_licenses.append(group["license"])
            for row in group["files"]:
                sources.append(row["name"] + "::" + row["url"])
                checksums.append(row["sha256"])
    if (root / "nacre/shell-tools/emoji-LICENSE.txt").is_file():
        core_licenses.append("Unicode-3.0")
    core = [
        "orient=" + lock["version"].replace("-dev.", "dev") if v == "orient" else v
        for v in mapping["core"]
    ]
    all_runtime = list(dict.fromkeys([*core, *mapping["ai"], *mapping["brain"]]))
    sessions = json.loads((root / "packaging/sessions.json").read_text())
    for definition in sessions.values():
        all_runtime += [
            value
            for value in mapping[definition["dependencies"]]
            if value not in all_runtime
        ]
    package_names = [
        "nacre",
        "nacre-ai",
        "nacre-brain",
        *(definition["package"] for definition in sessions.values()),
    ]
    session_functions = ""
    for name, definition in sessions.items():
        depends = array(
            ["nacre=$pkgver", *mapping[definition["dependencies"]]]
        ).replace("'nacre=$pkgver'", '"nacre=$pkgver"')
        session_functions += f"""
package_{definition["package"]}() {{
  pkgdesc='Nacre session integration for {definition["label"]}'
  arch=('any')
  depends={depends}
  cd "$srcdir/nacre"
  python packaging/arch/stage.py "$PWD" "$pkgdir" session-{name} "$srcdir/artifacts"
}}
"""
    return f"""# Generated by packaging/arch/recipe.py; edit packaging/packages.json for dependencies.
# Candidate recipe; prepare a new pinned recipe for every tested release.
# Maintainer: siverteh <92440237+Siverteh@users.noreply.github.com>
pkgbase=nacre
pkgname={array(package_names)}
pkgver={version}
pkgrel=1
pkgdesc='Desktop shell and guided per-user setup'
arch=('x86_64')
url='https://github.com/nacre-desktop/nacre'
license=('GPL-3.0-only')
# The Rust decoder links C archives; GCC LTO objects cannot be read by Rust's lld.
# Cargo's own release optimization and normal strip/debug processing remain enabled.
options=('!lto')
depends={array(all_runtime)}
makedepends={array(mapping["build"])}
checkdepends={array(mapping["check"])}
source={array(sources)}
sha256sums={array(checksums)}

prepare() {{
  cd "$srcdir/nacre"
  git submodule init
  git config submodule.deps/orient.url "$srcdir/orient"
  git -c protocol.file.allow=always submodule update
}}

build() {{
  cd "$srcdir/nacre"
  python -m build --wheel --no-isolation nacre/shell-cli
  python packaging/arch/build.py "$PWD" "$srcdir/artifacts" "$srcdir"
}}

check() {{
  cd "$srcdir/nacre"
  cargo test --locked --quiet
  cargo build --locked --examples
  npm ci --ignore-scripts --no-audit --no-fund
  python -m venv --system-site-packages "$srcdir/check-env"
  "$srcdir/check-env/bin/python" -m installer nacre/shell-cli/dist/*.whl
  export NACRE_HELPER_BINARY="$PWD/target/release/nacre-helper"
  export NACRE_ORIENT_BINARY=/usr/bin/orient
  python packaging/arch/check.py "$srcdir/check-env/bin/python"
}}

package_nacre() {{
  license={array(core_licenses)}
  depends={array(core)}
  optdepends={array(mapping["core_optional"])}
  cd "$srcdir/nacre"
  python -m installer --destdir="$pkgdir" nacre/shell-cli/dist/*.whl
  python packaging/arch/stage.py "$PWD" "$pkgdir" core "$srcdir/artifacts"
}}

package_nacre-ai() {{
  pkgdesc='Optional assistant workspace (no bundled providers or accounts)'
  arch=('any')
  depends={array(["nacre=$pkgver", *mapping["ai"]]).replace("'nacre=$pkgver'", '"nacre=$pkgver"')}
  optdepends={array(mapping["ai_optional"])}
  cd "$srcdir/nacre"
  python packaging/arch/stage.py "$PWD" "$pkgdir" ai "$srcdir/artifacts"
}}

package_nacre-brain() {{
  pkgdesc='Optional private Markdown knowledge library'
  arch=('any')
  depends={array(["nacre=$pkgver", *mapping["brain"]]).replace("'nacre=$pkgver'", '"nacre=$pkgver"')}
  optdepends={array(mapping["brain_optional"])}
  cd "$srcdir/nacre"
  python packaging/arch/stage.py "$PWD" "$pkgdir" brain "$srcdir/artifacts"
}}
{session_functions}"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", default="HEAD")
    parser.add_argument("--source-root", type=Path, default=ROOT)
    parser.add_argument(
        "--output", type=Path, default=Path(__file__).with_name("PKGBUILD")
    )
    args = parser.parse_args()
    revision = subprocess.check_output(
        ["git", "-C", str(args.source_root), "rev-parse", args.revision], text=True
    ).strip()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    sequence = subprocess.check_output(
        ["git", "-C", str(args.source_root), "rev-list", "--count", revision], text=True
    ).strip()
    args.output.write_text(render(args.source_root, revision, sequence))
