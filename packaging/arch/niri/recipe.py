#!/usr/bin/env python3
"""Generate the separate nacre-niri companion recipe at an exact Nacre revision."""

import argparse
import importlib.util
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[3]
spec = importlib.util.spec_from_file_location(
    "niri_stage", Path(__file__).with_name("stage.py")
)
stage = importlib.util.module_from_spec(spec)
spec.loader.exec_module(stage)


def array(values):
    return "(" + " ".join("'" + value + "'" for value in values) + ")"


def render(root, revision):
    mapping = json.loads((root / "packaging/packages.json").read_text())["arch"]
    return f"""# Generated by packaging/arch/niri/recipe.py; pinned source, no user hooks.
# Maintainer: siverteh <92440237+Siverteh@users.noreply.github.com>
pkgname=nacre-niri
pkgver=26.04
pkgrel=1
pkgdesc='Nacre Niri companion with native overview hover metadata'
arch=('x86_64')
url='https://github.com/nacre-desktop/nacre'
license=('GPL-3.0-or-later' 'GPL-3.0-only')
depends={array(mapping["niri"])}
makedepends={array(mapping["niri_build"])}
optdepends=('nacre: desktop shell with hover title display')
# GCC LTO objects in PipeWire's C shims cannot be consumed by Rust's lld linker.
# Niri's own Rust thin-LTO remains enabled; keep normal strip/debug processing.
options=('!lto')
source=('nacre::git+https://github.com/nacre-desktop/nacre.git#commit={revision}'
        'niri::git+https://github.com/niri-wm/niri.git#commit={stage.builder.SOURCE}')
sha256sums=('SKIP' 'SKIP')

prepare() {{
  python "$srcdir/nacre/packaging/arch/niri/stage.py" prepare "$srcdir/niri"
}}

build() {{
  cd "$srcdir/niri"
  cargo build --release --locked
}}

check() {{
  cd "$srcdir/niri"
  cargo test --release --locked --lib nacre_overview_hover_tests
}}

package() {{
  python "$srcdir/nacre/packaging/arch/niri/stage.py" stage "$srcdir/niri" "$pkgdir"
}}
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--revision", default="HEAD")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    revision = subprocess.check_output(
        ["git", "-C", str(ROOT), "rev-parse", args.revision], text=True
    ).strip()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(ROOT, revision))
